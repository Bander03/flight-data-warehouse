def mdx_script() -> str:
    lines = ["CALCULATE;"]
    for name, num, fmt in CALCULATED_MEMBERS:
        lines.append(
            f"CREATE MEMBER CURRENTCUBE.[Measures].[{name}] AS "
            f"IIF([Measures].[Segment Count] = 0, NULL, [Measures].[{num}] / [Measures].[Segment Count]), "
            f"FORMAT_STRING = \"{fmt}\", VISIBLE = 1;")
    return "\n".join(lines)


# ----------------------------------------------------------------------------- XML writer
class W:
    def __init__(self):
        self.lines = []
        self.depth = 0

    def raw(self, text):
        self.lines.append("  " * self.depth + text)

    def leaf(self, tag, value):
        self.raw(f"<{tag}>{escape(str(value))}</{tag}>")

    def open(self, tag, attrs=""):
        self.raw(f"<{tag}{attrs}>")
        self.depth += 1

    def close(self, tag):
        self.depth -= 1
        self.raw(f"</{tag}>")


def _xs_column(w, name, xs, size, nullable, calc=None):
    attrs = f" name={quoteattr(name)}"
    if calc is not None:
        attrs += (f' msdata:ReadOnly="true" msprop:DbColumnName={quoteattr(name)}'
                  f" msprop:ComputedColumnExpression={quoteattr(calc)}"
                  ' msprop:IsLogical="True"')
    else:
        attrs += f" msprop:DbColumnName={quoteattr(name)}"
    if nullable:
        attrs += ' minOccurs="0"'
    if xs == "string":
        w.open("xs:element", attrs)
        w.open("xs:simpleType")
        w.open('xs:restriction base="xs:string"')
        w.raw(f'<xs:maxLength value="{size}" />')
        w.close("xs:restriction")
        w.close("xs:simpleType")
        w.close("xs:element")
    else:
        w.raw(f"<xs:element{attrs} type={quoteattr(XS_TO_XSD[xs])} />")


def write_dsv(w):
    w.open("DataSourceView")
    w.leaf("ID", DSV)
    w.leaf("Name", DSV)
    w.leaf("DataSourceID", DS)
    w.open("Schema")
    w.open('xs:schema id="FlightDW" xmlns="" xmlns:xs="http://www.w3.org/2001/XMLSchema" '
           'xmlns:msdata="urn:schemas-microsoft-com:xml-msdata" '
           'xmlns:msprop="urn:schemas-microsoft-com:xml-msprop"')
    w.open('xs:element name="FlightDW" msdata:IsDataSet="true" msdata:UseCurrentLocale="true"')
    w.open("xs:complexType")
    w.open('xs:choice minOccurs="0" maxOccurs="unbounded"')
    for table, cols in TABLES.items():
        w.open(f'xs:element name="{tid(table)}" msprop:DbTableName="{table}" '
               f'msprop:FriendlyName="{table}" msprop:TableType="Table" msprop:DbSchemaName="dw"')
        w.open("xs:complexType")
        w.open("xs:sequence")
        for name, xs, size, nullable in cols:
            _xs_column(w, name, xs, size, nullable)
        for name, expr, xs, size in NAMED_CALCULATIONS.get(table, []):
            _xs_column(w, name, xs, size, True, calc=expr)
        w.close("xs:sequence")
        w.close("xs:complexType")
        w.close("xs:element")
    w.close("xs:choice")
    w.close("xs:complexType")
    for table, pk in PRIMARY_KEYS.items():
        w.open(f'xs:unique name="PK_{table}" msdata:PrimaryKey="true"')
        w.raw(f'<xs:selector xpath=".//{tid(table)}" />')
        w.raw(f'<xs:field xpath="{pk}" />')
        w.close("xs:unique")
    for fk, child, ccol, parent, _pcol in RELATIONSHIPS:
        w.open(f'xs:keyref name="{fk}" refer="PK_{parent}"')
        w.raw(f'<xs:selector xpath=".//{tid(child)}" />')
        w.raw(f'<xs:field xpath="{ccol}" />')
        w.close("xs:keyref")
    w.close("xs:element")
    w.close("xs:schema")
    w.close("Schema")
    w.close("DataSourceView")


def _data_item(w, tag, table, column, data_type=None, trimming=None):
    xs, size = _column_type(table, column)
    w.open(tag)
    w.leaf("DataType", data_type or XS_TO_SSAS[xs])
    if (data_type or XS_TO_SSAS[xs]) == "WChar":
        w.leaf("DataSize", size if xs == "string" else 50)
    if trimming:
        w.leaf("Trimming", trimming)
    w.open('Source xsi:type="ColumnBinding"')
    w.leaf("TableID", tid(table))
    w.leaf("ColumnID", column)
    w.close("Source")
    w.close(tag)


def write_dimension(w, dim):
    w.open("Dimension")
    w.leaf("ID", dim["name"])
    w.leaf("Name", dim["name"])
    w.open('Source xsi:type="DataSourceViewBinding"')
    w.leaf("DataSourceViewID", DSV)
    w.close("Source")
    w.leaf("UnknownMember", "None")
    w.leaf("Language", LANGUAGE)
    w.leaf("Collation", COLLATION)
    w.leaf("AttributeAllMemberName", "All")
    w.open("Attributes")
    for a in dim["attributes"]:
        w.open("Attribute")
        w.leaf("ID", a["name"])
        w.leaf("Name", a["name"])
        if a["usage"]:
            w.leaf("Usage", a["usage"])
        w.open("KeyColumns")
        _data_item(w, "KeyColumn", a["table"], a["key"], trimming=a["trim"])
        w.close("KeyColumns")
        if a["name_col"]:
            _data_item(w, "NameColumn", a["table"], a["name_col"], "WChar", a["trim"])
        if a["value"]:
            _data_item(w, "ValueColumn", a["table"], a["value"])
        if a["related"]:
            w.open("AttributeRelationships")
            for r in a["related"]:
                w.open("AttributeRelationship")
                w.leaf("AttributeID", r)
                w.leaf("Name", r)
                w.close("AttributeRelationship")
            w.close("AttributeRelationships")
        w.leaf("OrderBy", a["order"])
        w.close("Attribute")
    w.close("Attributes")
    if dim["hierarchies"]:
        w.open("Hierarchies")
        for hname, levels in dim["hierarchies"]:
            w.open("Hierarchy")
            w.leaf("ID", hname)
            w.leaf("Name", hname)
            w.leaf("AllMemberName", "All")
            w.open("Levels")
            for lv in levels:
                w.open("Level")
                w.leaf("ID", lv)
                w.leaf("Name", lv)
                w.leaf("SourceAttributeID", lv)
                w.close("Level")
            w.close("Levels")
            w.close("Hierarchy")
        w.close("Hierarchies")
    w.close("Dimension")


def _key_attribute(dbdim):
    for d in DIMENSIONS:
        if d["name"] == dbdim:
            return next(a["name"] for a in d["attributes"] if a["usage"] == "Key")
    raise KeyError(dbdim)


def write_cube(w):
    w.open("Cube")
    w.leaf("ID", DB)
    w.leaf("Name", DB)
    w.leaf("Language", LANGUAGE)
    w.leaf("Collation", COLLATION)
    w.open("Dimensions")
    for cname, dbdim, _fk in CUBE_DIMENSIONS:
        w.open("Dimension")
        w.leaf("ID", cname)
        w.leaf("Name", cname)
        w.leaf("DimensionID", dbdim)
        w.close("Dimension")
    w.close("Dimensions")
    w.open("MdxScripts")
    w.open("MdxScript")
    w.leaf("ID", "MdxScript")
    w.leaf("Name", "MdxScript")
    w.open("Commands")
    w.open("Command")
    w.leaf("Text", mdx_script())
    w.close("Command")
    w.close("Commands")
    w.close("MdxScript")
    w.close("MdxScripts")
    w.leaf("DefaultMeasure", DEFAULT_MEASURE)
    w.leaf("StorageMode", "Molap")
    w.open("MeasureGroups")
    for mg_name, measures in MEASURE_GROUPS:
        w.open("MeasureGroup")
        w.leaf("ID", mg_name)
        w.leaf("Name", mg_name)
        w.open("Measures")
        for name, agg, col, dtype, visible, fmt in measures:
            w.open("Measure")
            w.leaf("ID", name)
            w.leaf("Name", name)
            w.leaf("AggregateFunction", agg)
            w.leaf("DataType", dtype)
            # SSAS requires the source data type to equal the measure data type for Sum measures;
            # the server converts the TINYINT/INT/DECIMAL columns while reading.
            _data_item(w, "Source", FACT, col, dtype)
            if not visible:
                w.leaf("Visible", "false")
            w.leaf("FormatString", fmt)
            w.close("Measure")
        w.close("Measures")
        w.leaf("StorageMode", "Molap")
        w.leaf("ProcessingMode", "Regular")
        w.open("Dimensions")
        for cname, dbdim, fk in CUBE_DIMENSIONS:
            w.open('Dimension xsi:type="RegularMeasureGroupDimension"')
            w.leaf("CubeDimensionID", cname)
            w.open("Attributes")
            w.open("Attribute")
            w.leaf("AttributeID", _key_attribute(dbdim))
            w.open("KeyColumns")
            _data_item(w, "KeyColumn", FACT, fk)
            w.close("KeyColumns")
            w.leaf("Type", "Granularity")
            w.close("Attribute")
            w.close("Attributes")
            w.close("Dimension")
        w.close("Dimensions")
        w.open("Partitions")
        w.open("Partition")
        w.leaf("ID", mg_name)
        w.leaf("Name", mg_name)
        w.open('Source xsi:type="DsvTableBinding"')
        w.leaf("DataSourceViewID", DSV)
        w.leaf("TableID", tid(FACT))
        w.close("Source")
        w.leaf("StorageMode", "Molap")
        w.close("Partition")
        w.close("Partitions")
        w.close("MeasureGroup")
    w.close("MeasureGroups")
    w.open('Source xsi:type="DataSourceViewBinding"')
    w.leaf("DataSourceViewID", DSV)
    w.close("Source")
    w.close("Cube")


def build_xmla() -> str:
    w = W()
    # No XML declaration and no comment before the root: Invoke-ASCmd only recognises a request as
    # XMLA when the text starts with the command element (otherwise it is parsed as MDX).
    w.open('Create AllowOverwrite="true" xmlns="http://schemas.microsoft.com/analysisservices/2003/engine"')
    w.raw("<!--")
    for line in HEADER.splitlines():
        w.raw("  " + line)
    w.raw("-->")
    w.open("ObjectDefinition")
    w.open('Database xmlns:xsd="http://www.w3.org/2001/XMLSchema" '
           'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"')
    w.leaf("ID", DB)
    w.leaf("Name", DB)
    w.leaf("Language", LANGUAGE)
    w.leaf("Collation", COLLATION)
    w.open("DataSourceImpersonationInfo")
    w.leaf("ImpersonationMode", "Default")
    w.close("DataSourceImpersonationInfo")
    w.open("Dimensions")
    for dim in DIMENSIONS:
        write_dimension(w, dim)
    w.close("Dimensions")
    w.open("Cubes")
    write_cube(w)
    w.close("Cubes")
    w.open("DataSources")
    w.open('DataSource xsi:type="RelationalDataSource"')
    w.leaf("ID", DS)
    w.leaf("Name", DS)
    w.leaf("ConnectionString", CONNECTION)
    w.open("ImpersonationInfo")
    w.leaf("ImpersonationMode", "ImpersonateServiceAccount")
    w.close("ImpersonationInfo")
    w.leaf("Timeout", "PT0S")
    w.close("DataSource")
    w.close("DataSources")
    w.open("DataSourceViews")
    write_dsv(w)
    w.close("DataSourceViews")
    w.close("Database")
    w.close("ObjectDefinition")
    w.close("Create")
    return "\n".join(w.lines) + "\n"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(build_xmla())
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
