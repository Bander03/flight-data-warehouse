"""Builds mdx/results/SUMMARY.md from the MDX result CSVs (Plan 2, Task 6).

Per statement: stem, operation, business question and measure (from the `.mdx` header comments),
the number of result rows and the first 5 rows. Facts from the results only, no interpretation.

Usage (repo root, after powershell -File tools\\run_mdx.ps1):
    python tools/make_results_summary.py              # results only
    python tools/make_results_summary.py --compare    # also runs tools/compare_results.py and states
                                                      # the cross-check outcome in the header
Without --compare the summary makes no claim about the cross-check.
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import compare_results as cr   # noqa: E402

FIRST_ROWS = 5


def _header(text: str, tag: str) -> str:
    m = re.search(rf"^--\s*{tag}:[ \t]*(.+)$", text, re.M)
    return m.group(1).strip() if m else "(missing)"


def _fmt(value: str) -> str:
    f = float(value)
    return str(int(f)) if f == int(f) else f"{f:.4f}".rstrip("0").rstrip(".")


def build_summary(mdx_dir: Path, results_dir: Path, compare_status: str | None = None) -> str:
    out = ["# MDX results summary", "",
           "Generated by `tools/make_results_summary.py` from `mdx/results/<stem>.csv` "
           "(written by `tools/run_mdx.ps1` against the processed cube `FlightCube`).",
           "Values are the raw cell values, shown rounded to at most 4 decimals here; "
           "the CSV files hold the full values."]
    if compare_status:
        out.append(f"Cross-check with the T-SQL answer keys (`tools/compare_results.py`, "
                   f"{date.today().isoformat()}): {compare_status}.")
    out.append("")
    for p in sorted(Path(mdx_dir).glob("*.mdx")):
        stem, text = p.stem, p.read_text(encoding="utf-8")
        ranked = stem.startswith(cr.RANKED)
        out += [f"## {stem}", "", f"- Operation: {_header(text, 'Operation')}",
                f"- Question: {_header(text, 'Question')}", f"- Measure: {_header(text, 'Measure')}"]
        csv_path = Path(results_dir) / f"{stem}.csv"
        if not csv_path.exists():
            out += [f"- Rows: no result file (run tools/run_mdx.ps1)", ""]
            continue
        rows = cr.load_result(csv_path)
        cols = ["Rank", "Member", "Value"] if ranked else ["Member", "Value"]
        out += [f"- Rows: {len(rows)}", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        for r in rows[:FIRST_ROWS]:
            cells = ([r["Rank"]] if ranked else []) + [r["Member"].replace("|", "\\|"), _fmt(r["Value"])]
            out.append("| " + " | ".join(cells) + " |")
        out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--mdx-dir", type=Path, default=cr.MDX_DIR)
    ap.add_argument("--results-dir", type=Path, default=cr.RESULTS)
    ap.add_argument("--compare", action="store_true", help="run the answer-key cross-check and state its outcome")
    args = ap.parse_args(argv)
    status_text = None
    if args.compare:
        sqlcmd = shutil.which("sqlcmd")
        if sqlcmd is None:
            print("ERROR: sqlcmd is not on PATH (needed for --compare)")
            return 1
        stems = sorted(p.stem for p in args.mdx_dir.glob("*.mdx"))
        status = cr.check(stems, sqlcmd)
        status_text = cr.summary_line(status)
        failed = [s for s, d in status.items() if d]
        if failed:
            status_text += f" (mismatch: {', '.join(failed)})"
    target = args.results_dir / "SUMMARY.md"
    target.write_text(build_summary(args.mdx_dir, args.results_dir, status_text).rstrip("\n") + "\n",
                      encoding="utf-8", newline="\n")
    print(f"wrote {target}" + (f"; {status_text}" if status_text else ""))
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main(sys.argv[1:]))
