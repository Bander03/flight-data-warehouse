"""Tests of the scripted cube build (Plan 2, Task 5b).

Offline (default): ssas/FlightCube.xmla is generated by tools/build_cube_xmla.py, is well-formed
XML and implements docs/cube-spec.md (registry names, role-playing, measure types, named
calculations, no secrets).

Live (opt-in, FDW_CUBE_TESTS=1): runs tools/deploy_cube.ps1 -SmokeOnly against the deployed and
processed Analysis Services database FlightCube and checks the Plan 1 totals. Default runs never
touch the server.
"""
import importlib.util
import os
import re
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
XMLA = REPO / "ssas" / "FlightCube.xmla"
SPEC = REPO / "docs" / "cube-spec.md"
GENERATOR = REPO / "tools" / "build_cube_xmla.py"
DEPLOY = REPO / "tools" / "deploy_cube.ps1"

ENG = "{http://schemas.microsoft.com/analysisservices/2003/engine}"
XS = "{http://www.w3.org/2001/XMLSchema}"
MSPROP = "{urn:schemas-microsoft-com:xml-msprop}"
XSI_TYPE = "{http://www.w3.org/2001/XMLSchema-instance}type"


def _root():
    return ET.parse(XMLA).getroot()


def _database():
    db = _root().find(f".//{ENG}Database")
    assert db is not None, "no Database element"
    return db


def _registry():
    block = SPEC.read_text(encoding="utf-8").split("## 6. Names registry", 1)[1]
    reg = {}
    for line in block.splitlines():
        m = re.match(r"^([a-z ]+):\s+(.+)$", line.strip())
        if m:
            reg.setdefault(m.group(1), set()).add(m.group(2).strip())
    return reg


def _spec_named_calculations():
    """{(table, name): expression} from the spec's 'DSV named calculations' table."""
    text = SPEC.read_text(encoding="utf-8")
    block = text.split("### DSV named calculations", 1)[1].split("## 2.", 1)[0]
    out = {}
    for line in block.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or not cells[0].startswith("`"):
            continue
        # The expression may itself contain '|'-free text only; take the first backticked span.
        rest = "|".join(cells[2:])
        expr = re.match(r"`([^`]+)`", rest).group(1)
        out[(cells[0].strip("`"), cells[1].strip("`"))] = expr
    return out


def _text(el, path):
    found = el.find(path)
    return None if found is None else (found.text or "")


def _cube():
    cube = _database().find(f"{ENG}Cubes/{ENG}Cube")
    assert cube is not None
    return cube


def _measure_groups():
    return {_text(mg, f"{ENG}Name"): mg for mg in _cube().findall(f"{ENG}MeasureGroups/{ENG}MeasureGroup")}


# ----------------------------------------------------------------------------- offline tests

def test_xmla_well_formed():
    root = _root()
    assert root.tag == f"{ENG}Create"
    assert root.get("AllowOverwrite") == "true"
    db = _database()
    assert _text(db, f"{ENG}ID") == "FlightCube" and _text(db, f"{ENG}Name") == "FlightCube"


def test_xmla_is_generated_and_current():
    assert _generator().build_xmla() == XMLA.read_text(encoding="utf-8"), \
        "ssas/FlightCube.xmla is stale: run python tools/build_cube_xmla.py"


def test_registry_names_present():
    reg = _registry()
    db = _database()
    names = {el.text for el in db.iter(f"{ENG}Name")}
    script = " ".join(el.text or "" for el in db.iter(f"{ENG}Text"))
    missing = []
    for kind, values in reg.items():
        if kind == "member":            # data values, not metadata
            continue
        for v in values:
            if kind == "calculated member":
                if f"[Measures].[{v}]" not in script:
                    missing.append(f"{kind}: {v}")
            elif v not in names:
                missing.append(f"{kind}: {v}")
    assert not missing, missing


def test_seven_database_dimensions_and_hierarchies():
    db = _database()
    dims = {_text(d, f"{ENG}Name"): d for d in db.findall(f"{ENG}Dimensions/{ENG}Dimension")}
    assert set(dims) == {"Date", "Passenger", "Airport", "Flight", "Plane", "Cabin", "Price Range"}
    hier = {}
    for dname, d in dims.items():
        for h in d.findall(f"{ENG}Hierarchies/{ENG}Hierarchy"):
            hier[_text(h, f"{ENG}Name")] = (dname, [_text(l, f"{ENG}Name") for l in h.findall(f"{ENG}Levels/{ENG}Level")])
    assert hier == {
        "Calendar": ("Date", ["Year", "Quarter", "Month", "Day"]),
        "Geography": ("Airport", ["Province", "Airport"]),
        "Airline Flight": ("Flight", ["Airline", "Flight No", "Ticket"]),
        "Plane Class": ("Plane", ["Size Class", "Plane Model"]),
    }


def test_role_playing():
    cube = _cube()
    cube_dims = {_text(d, f"{ENG}Name"): _text(d, f"{ENG}DimensionID")
                 for d in cube.findall(f"{ENG}Dimensions/{ENG}Dimension")}
    assert cube_dims == {
        "Departure Date": "Date", "Arrival Date": "Date", "Passenger": "Passenger",
        "Departure Airport": "Airport", "Transit Airport": "Airport", "Landing Airport": "Airport",
        "Flight": "Flight", "Plane": "Plane", "Cabin": "Cabin", "Price Range": "Price Range",
    }
    expected_fk = {
        "Departure Date": "DepartureDateKey", "Arrival Date": "ArrivalDateKey",
        "Passenger": "PassengerKey", "Departure Airport": "DepartureAirportKey",
        "Transit Airport": "TransitAirportKey", "Landing Airport": "LandingAirportKey",
        "Flight": "TicketKey", "Plane": "PlaneKey", "Cabin": "CabinKey", "Price Range": "PriceRangeKey",
    }
    for mg_name, mg in _measure_groups().items():
        usage = {}
        for d in mg.findall(f"{ENG}Dimensions/{ENG}Dimension"):
            assert d.get(XSI_TYPE) == "RegularMeasureGroupDimension"
            col = d.find(f"{ENG}Attributes/{ENG}Attribute/{ENG}KeyColumns/{ENG}KeyColumn/{ENG}Source/{ENG}ColumnID")
            usage[_text(d, f"{ENG}CubeDimensionID")] = col.text
        assert usage == expected_fk, mg_name


def test_measure_types():
    mgs = _measure_groups()
    assert set(mgs) == {"Flight Segments", "Segment Passengers"}
    found = {}
    for mg_name, mg in mgs.items():
        for m in mg.findall(f"{ENG}Measures/{ENG}Measure"):
            found[_text(m, f"{ENG}Name")] = (
                mg_name, _text(m, f"{ENG}AggregateFunction") or "Sum", _text(m, f"{ENG}DataType"),
                _text(m, f"{ENG}Visible") != "false", _text(m, f"{ENG}FormatString"),
                _text(m, f"{ENG}Source/{ENG}Source/{ENG}ColumnID"))
    assert found == {
        "Segment Count": ("Flight Segments", "Sum", "BigInt", True, "#,##0", "SegmentCount"),
        "Total Price": ("Flight Segments", "Sum", "BigInt", True, "#,##0", "Price"),
        "Total Mileage": ("Flight Segments", "Sum", "BigInt", True, "#,##0", "Mileage"),
        "Stopover Segments": ("Flight Segments", "Sum", "BigInt", True, "#,##0", "HasStopover"),
        "Rate Sum": ("Flight Segments", "Sum", "Double", False, "#,##0.00", "Rate"),
        "Distinct Passengers": ("Segment Passengers", "DistinctCount", "Integer", True, "#,##0", "PassengerKey"),
    }
    assert _text(_cube(), f"{ENG}DefaultMeasure") == "[Measures].[Segment Count]"


def test_calculated_members():
    script = " ".join(el.text or "" for el in _cube().iter(f"{ENG}Text"))
    for name, num, fmt in [("Average Price", "Total Price", "#,##0.00"),
                           ("Average Rate", "Rate Sum", "0.000"),
                           ("Stopover Share", "Stopover Segments", "0.0%")]:
        expected = (f"CREATE MEMBER CURRENTCUBE.[Measures].[{name}] AS "
                    f"IIF([Measures].[Segment Count] = 0, NULL, [Measures].[{num}] / [Measures].[Segment Count]), "
                    f"FORMAT_STRING = \"{fmt}\"")
        assert expected in script, name


def _generator():
    spec = importlib.util.spec_from_file_location("build_cube_xmla", GENERATOR)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_named_calculations_match_spec():
    """Every named calculation equals the spec text, except documented spec deviations, which must
    name the current spec text and be listed in the XMLA header comment."""
    spec = _spec_named_calculations()
    assert len(spec) == 12
    header = XMLA.read_text(encoding="utf-8").split("-->", 1)[0]
    for key, (spec_expr, used_expr, _why) in _generator().SPEC_DEVIATIONS.items():
        assert spec[key] == spec_expr, f"deviation {key} refers to outdated spec text"
        assert f"{key[0]}.{key[1]}" in header and used_expr in header
        spec[key] = used_expr
    dsv = {}
    for table in _database().iter(f"{XS}element"):
        tname = table.get(f"{MSPROP}DbTableName")
        if not tname:
            continue
        for col in table.iter(f"{XS}element"):
            expr = col.get(f"{MSPROP}ComputedColumnExpression")
            if expr is not None:
                dsv[(tname, col.get("name"))] = expr
    assert dsv == spec


def test_dsv_tables_and_relationships():
    db = _database()
    tables = {el.get(f"{MSPROP}DbTableName") for el in db.iter(f"{XS}element") if el.get(f"{MSPROP}DbTableName")}
    assert tables == {"DimDate", "DimPassenger", "DimAirline", "DimTicket", "DimAirport", "DimPlane",
                      "DimSeat", "DimPriceRange", "Fact_FlightSegment"}
    assert len(list(db.iter(f"{XS}keyref"))) == 11


def test_data_source_and_storage():
    db = _database()
    ds = db.find(f"{ENG}DataSources/{ENG}DataSource")
    cs = _text(ds, f"{ENG}ConnectionString")
    assert "localhost\\SQLEXPRESS" in cs and "Initial Catalog=FlightDW" in cs
    assert "Integrated Security=SSPI" in cs
    assert _text(ds, f"{ENG}ImpersonationInfo/{ENG}ImpersonationMode") == "ImpersonateServiceAccount"
    for mg in _measure_groups().values():
        assert _text(mg, f"{ENG}StorageMode") == "Molap"


def test_no_secrets():
    text = XMLA.read_text(encoding="utf-8")
    for pattern in [r"password\s*=", r"pwd\s*=", r"user\s*id\s*=", r"\buid\s*=", r"<Password>",
                    r"<Account>", r"ImpersonateAccount"]:
        assert not re.search(pattern, text, re.IGNORECASE), pattern


# ----------------------------------------------------------------------------- live test (opt-in)

@pytest.mark.skipif(os.environ.get("FDW_CUBE_TESTS") != "1", reason="set FDW_CUBE_TESTS=1 to query the live cube")
def test_live_smoke():
    out = subprocess.run(
        ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(DEPLOY), "-SmokeOnly"],
        capture_output=True, text=True, encoding="utf-8", timeout=600)
    assert out.returncode == 0, out.stdout + out.stderr
    values = dict(re.findall(r"^SMOKE\s+(.+?)\s*=\s*(\S+)\s*$", out.stdout, re.MULTILINE))
    assert float(values["Segment Count"]) == 600
    assert float(values["Stopover Segments"]) == 95
    assert float(values["Total Price"]) == 1400460
    assert float(values["Distinct Passengers"]) == 599
    assert float(values["Average Price"]) == pytest.approx(2334.10, abs=0.01)
